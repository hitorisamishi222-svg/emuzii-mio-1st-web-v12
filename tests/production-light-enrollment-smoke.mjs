import assert from 'node:assert/strict';
import {randomBytes} from 'node:crypto';
const origin='https://emuzii-mio-1st-web-v12.vercel.app';
const key=randomBytes(32).toString('hex');
const name='V2_SMOKE_TEST_20261019';
const payload={name,retryKey:key,retryIssuedAt:Date.now()};
const noRedirect={redirect:'follow',signal:AbortSignal.timeout(25000)};
async function get(path){return fetch(origin+path,{...noRedirect,cache:'no-store'})}
const landing=await get('/join.html');
assert.equal(landing.status,200,'Join page fails to load');
const html=await landing.text();
for(const part of ['/api/enroll-lite','/gallery.html','docs.google.com/forms/d/e/'])assert.ok(html.includes(part),'missing link '+part);
console.log('PASS public registration page and form/gallery links');
const gallery=await get('/gallery.html');
assert.equal(gallery.status,200,'Gallery does not load');
const galleryBody=await gallery.text();
assert.ok(galleryBody.includes('翠央っ子'));
const entries=await get('/api/gallery/items');
assert.equal(entries.status,200,'Published gallery items API unavailable');
const items=await entries.json();
assert.ok(items.ok&&Array.isArray(items.items),'Invalid gallery response');
console.log('PASS gallery view and published gallery data, items='+items.items.length);
const current=await get('/api/enroll-lite');
assert.equal(current.status,200);
const original=await current.json();
assert.equal(original.registered,false,'Unauthenticated test is already registered');
console.log('PASS unauthenticated landing');
const enroll=await fetch(origin+'/api/enroll-lite',{...noRedirect,method:'POST',headers:{'Content-Type':'application/json','Origin':origin},body:JSON.stringify(payload)});
const response=await enroll.json();
assert.equal(enroll.status,201,'New enrollment did not save: '+JSON.stringify(response));
assert.ok(response.ok&&response.registered&&response.participantId?.startsWith('MIO-W-'),'No registered ID returned');
const cookie=enroll.headers.get('set-cookie')?.split(';')[0];
assert.ok(cookie?.startsWith('mio_light_session='),'No signed session cookie');
console.log('PASS POST: new basic enrollment persists and sets session, browser ID='+response.participantId);
const after=await fetch(origin+'/api/enroll-lite',{...noRedirect,headers:{Cookie:cookie}});
assert.equal(after.status,200,'Registered browser unable to view enrollment');
const result=await after.json();
assert.ok(result.ok&&result.registered&&result.participantId===response.participantId,'Registration retrieval mismatch');
console.log('PASS GET: registered user authenticated readback');
const second=await fetch(origin+'/api/enroll-lite',{...noRedirect,method:'POST',headers:{'Content-Type':'application/json','Origin':origin,'Cookie':cookie},body:JSON.stringify(payload)});
assert.equal(second.status,200,'Idempotent repeat incorrect');
console.log('PASS already registered browser does not create duplicate');
console.log('SUCCESS: live registration and accessible entry points; test name='+name);
